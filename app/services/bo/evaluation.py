"""Evaluate a BO run against a reviewer-controlled manifest.

The manifest is written and verified by a human reviewer from the SOURCE filing;
it is never generated by the model under test, and it is not the groupmate's
reference prose. Checks are concept-level (regular expressions over claims and
verified quotes) and grounding-level (does the source say it, is the number's
basis right) — never a wording comparison.

Four dimensions are reported separately: factual correctness, analytical
reasoning, completeness and execution reliability. Nothing here produces a
single "accuracy" number, and a manifest that has not been reviewer-verified
against the processed filing is reported as such: its results are diagnostics,
not a correctness claim.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from app.services.bo.hypotheses import normalise, quote_in_passage

MANIFEST_VERSION = "bo-review-manifest-1.0"
VERIFIED = "reviewer_verified"


def load_manifest(path: str | Path) -> dict[str, Any]:
    manifest = json.loads(Path(path).read_text(encoding="utf-8"))
    if manifest.get("manifest_version") != MANIFEST_VERSION:
        raise ValueError(f"Unsupported review manifest version in {path}.")
    return manifest


def _all(patterns, text: str) -> bool:
    return all(re.search(p, text, re.I | re.S) for p in patterns)


def _any(patterns, text: str) -> bool:
    return any(re.search(p, text, re.I | re.S) for p in patterns)


def _text(hypothesis: dict[str, Any]) -> str:
    quotes = " ".join(q["quote"] for q in hypothesis.get("evidence_quotes") or [])
    return f"{hypothesis.get('claim', '')} {quotes}"


def evaluate_run(manifest: dict[str, Any], *, memo: dict[str, Any],
                 audit: dict[str, Any], evidence) -> dict[str, Any]:
    passages = {p["evidence_id"]: p.get("text") or ""
                for p in evidence.narrative_evidence}
    corpus = normalise(" ".join(passages.values()))
    current = [h for h in audit["hypotheses"]["records"]
               if h["acceptance_state"] == "accepted"]
    usable = [h for h in current if h["admissibility"] != "audit_only"]
    established = [h for h in usable if h["admissibility"] == "established"]
    memo_claims = [c for s in memo["sections"] for c in s["claims"]]
    memo_claims += memo["strengths_vulnerabilities"]["strengths"]
    memo_claims += memo["strengths_vulnerabilities"]["weaknesses"]
    if memo["executive"]["provisional_view"]:
        memo_claims.append(memo["executive"]["provisional_view"])
    memo_texts = [c["text"] for c in memo_claims]
    by_param = {c["parameter_id"]: c for c in audit["calculations"]}

    # -- 1. factual correctness ------------------------------------------------
    citations = checked = 0
    invalid = []
    for h in usable:
        for eid in {*h["supporting_evidence_ids"], *h["contradicting_evidence_ids"]}:
            citations += 1
            if eid in passages:
                checked += 1
            else:
                invalid.append({"hypothesis_id": h["hypothesis_id"], "evidence_id": eid})
        for quote in h["evidence_quotes"]:
            citations += 1
            if quote_in_passage(quote["quote"], passages.get(quote["evidence_id"], "")):
                checked += 1
            else:
                invalid.append({"hypothesis_id": h["hypothesis_id"],
                                "quote": quote["quote"][:80]})
    facts = []
    for fact in manifest.get("source_confirmed_facts", []):
        quote = fact.get("verified_quote")
        located = (normalise(quote) in corpus if quote
                   else _all(fact.get("source_patterns", []), corpus))
        covering = [h["hypothesis_id"] for h in usable
                    if _all(fact.get("finding_patterns")
                            or fact.get("source_patterns", []), _text(h))]
        facts.append({"id": fact["id"], "concept": fact.get("concept"),
                      "located_in_admitted_evidence": located,
                      "verified_quote_supplied": bool(quote),
                      "covered_by": covering})
    values = []
    for item in manifest.get("recomputed_values", []):
        trace = by_param.get(item["parameter_id"])
        expected, tolerance = item.get("expected_value"), item.get("tolerance", 1e-6)
        values.append({
            "id": item["id"], "parameter_id": item["parameter_id"],
            "expected": expected,
            "calculated": trace["value"] if trace else None,
            "denominator": (trace.get("denominator") or {}).get("name") if trace else None,
            "match": bool(trace) and expected is not None and trace["value"] is not None
            and abs(trace["value"] - expected) <= tolerance
            and item.get("denominator") in (
                None, (trace.get("denominator") or {}).get("name")),
        })
    factual = {
        "citation_references_checked": citations,
        "citation_references_valid": checked,
        "citation_validity": (checked / citations) if citations else None,
        "invalid_references": invalid,
        "source_confirmed_facts": facts,
        "facts_located": sum(f["located_in_admitted_evidence"] for f in facts),
        "facts_covered": sum(bool(f["covered_by"]) for f in facts),
        "recomputed_values": values,
    }

    # -- 2. analytical reasoning -----------------------------------------------
    false_results = []
    for item in manifest.get("known_false_hypotheses", []):
        asserted = [h["hypothesis_id"] for h in usable
                    if _all(item["patterns"], h["claim"])]
        asserted += [f"memo:{c['claim_id']}" for c in memo_claims
                     if _all(item["patterns"], c["text"])]
        rejected = [h["hypothesis_id"] for h in current
                    if h["disposition"] == "rejected"
                    and _all(item["patterns"], h["claim"])]
        false_results.append({"id": item["id"], "asserted_by": asserted,
                              "explicitly_rejected_by": rejected,
                              "passed": not asserted})
    traps = [_trap(check, usable, established, memo_claims)
             for check in manifest.get("trap_checks", [])]
    inferences = [
        {"id": item["id"],
         "found_in": [h["hypothesis_id"] for h in usable
                      if _all(item["patterns"], h["claim"])]}
        for item in manifest.get("acceptable_inferences", [])]
    reasoning = {
        "known_false_hypotheses": false_results,
        "false_hypotheses_avoided": sum(r["passed"] for r in false_results),
        "trap_checks": traps,
        "trap_checks_passed": sum(t["passed"] for t in traps),
        "acceptable_inferences": inferences,
        "qualified_or_attributed_findings": sum(
            h["admissibility"] in ("qualified_narrative", "attributed") for h in usable),
        "findings_with_counter_evidence": sum(
            bool(h["contradicting_evidence_ids"]) for h in usable),
    }

    # -- 3. completeness -------------------------------------------------------
    coverage = manifest.get("expected_coverage", {})
    sections = {s["code"]: len(s["claims"]) + len(s.get("headline_refs", []))
                for s in memo["sections"]}
    concepts = []
    for concept in coverage.get("concepts", []):
        found = [t for t in memo_texts if _all(concept["patterns"], t)]
        in_findings = [h["hypothesis_id"] for h in usable
                       if _all(concept["patterns"], _text(h))]
        concepts.append({"id": concept["id"], "kind": concept.get("kind", "risk"),
                         "in_memo": bool(found), "in_validated_findings": in_findings})
    questions = [
        {"id": q["id"],
         "identified": _any(q["patterns"], " ".join(
             [*memo["outstanding"]["open_questions"],
              *memo["outstanding"]["missing_information"],
              *audit["missing_information"]]))}
        for q in manifest.get("known_unresolved_questions", [])]
    completeness = {
        "sections_expected": coverage.get("sections", []),
        "sections_with_findings": sorted(c for c, n in sections.items() if n),
        "sections_missing": sorted(
            c for c in coverage.get("sections", []) if not sections.get(c)),
        "concepts": concepts,
        "concept_recall_in_memo": _rate(c["in_memo"] for c in concepts),
        "concept_recall_in_findings": _rate(
            bool(c["in_validated_findings"]) for c in concepts),
        "unresolved_questions": questions,
        "unresolved_question_recall": _rate(q["identified"] for q in questions),
        "duplicate_memo_findings": len(memo_texts) - len(set(memo_texts)),
    }

    # -- 4. execution reliability ----------------------------------------------
    agents = {a["agent_id"]: a["status"] for a in audit["agents"]}
    runs = [r for a in audit["agents"] for r in a["runs"]]
    reliability = {
        "agents": agents,
        "agents_validated": sum(s == "validated" for s in agents.values()),
        "agent_runs": len(runs),
        "runs_rejected": sum(r["validation_status"] != "valid" for r in runs),
        "validation_rejection_rate": _rate(
            r["validation_status"] != "valid" for r in runs),
        "ai_calls": audit["execution"]["ai_calls"],
        "cache_reuses": audit["execution"]["cache_reuses"],
        "rerun": audit["rerun"] if isinstance(audit["rerun"], str) else "performed",
        "runtime_seconds": audit["execution"]["runtime_seconds"],
        "token_usage": audit["execution"]["token_usage"],
        "per_agent_usage": {a["agent_id"]: [r["usage"] for r in a["runs"]]
                            for a in audit["agents"]},
    }

    status = manifest.get("verification_status", "unverified")
    return {
        "document": "business_overview_evaluation",
        "manifest_version": manifest["manifest_version"],
        "borrower": manifest.get("borrower"),
        "analysis_run_id": audit["run"]["analysis_run_id"],
        "execution_mode": audit["run"]["execution_mode"],
        "ground_truth_status": status,
        "interpretation": (
            "Manifest verified by a reviewer against the processed filing."
            if status == VERIFIED else
            "The manifest has NOT been reviewer-verified against the processed "
            "filing. These results are diagnostics, not evidence of correctness."
        ) + (" Responses were scripted (offline simulation), so this measures the "
             "pipeline and the script, not a model."
             if audit["run"]["execution_mode"] == "offline_simulation" else ""),
        "factual_correctness": factual,
        "analytical_reasoning": reasoning,
        "completeness": completeness,
        "execution_reliability": reliability,
    }


def _rate(flags) -> float | None:
    flags = list(flags)
    return (sum(bool(f) for f in flags) / len(flags)) if flags else None


def _trap(check, usable, established, memo_claims) -> dict[str, Any]:
    """One interpretive trap: a required reading and forbidden over-readings."""
    problems = []
    everything = [(h["hypothesis_id"], _text(h)) for h in usable]
    everything += [(f"memo:{c['claim_id']}", c["text"]) for c in memo_claims]
    required = check.get("required_all")
    if required and not any(_all(required, text) for _, text in everything):
        problems.append("required reading not found")
    for pattern in check.get("forbidden", []):
        problems += [f"{ref} asserts the forbidden reading /{pattern}/"
                     for ref, text in everything if re.search(pattern, text, re.I)]
    for pattern in check.get("forbidden_as_established", []):
        problems += [
            f"{h['hypothesis_id']} presents /{pattern}/ as an established fact"
            for h in established if re.search(pattern, h["claim"], re.I)]
        problems += [
            f"memo:{c['claim_id']} presents /{pattern}/ as fact"
            for c in memo_claims if c.get("claim_type") in ("fact", "calculated_fact")
            and re.search(pattern, c["text"], re.I)]
    basis = check.get("number_basis")
    if basis:
        for h in usable:
            claim = h["claim"]
            if not _all(basis["scope"], claim) or not re.search(r"\d\s?%", claim):
                continue
            support = " ".join(
                [*(q["quote"] for q in h["evidence_quotes"]),
                 *(str(q.get("denominator") or "") for q in h["quoted_values"])])
            for term in basis["terms"]:
                if re.search(term, claim, re.I) and not re.search(term, support, re.I):
                    problems.append(
                        f"{h['hypothesis_id']} states a share of {term!r} that its "
                        "source quote or calculation does not describe")
    if check.get("mitigant_must_be_unproven"):
        for h in usable:
            if h.get("mitigant") and _all(check["mitigant_must_be_unproven"], _text(h)):
                if h["mitigant"]["effectiveness"] == "demonstrated" and not (
                        h["mitigant"]["outcome_evidence_ids"]):
                    problems.append(
                        f"{h['hypothesis_id']} treats the initiative as proven")
    return {"id": check["id"], "description": check.get("description"),
            "passed": not problems, "problems": problems}
